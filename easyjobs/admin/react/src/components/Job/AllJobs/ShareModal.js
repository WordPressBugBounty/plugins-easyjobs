const buildShareLinks = (job) => {
  if (!job) {
    return {
      facebook: '',
      linkedIn: '',
      twitter: '',
      viewUrl: '',
    };
  }

  const viewUrl = job?.view_url || '';
  const title = job?.title || '';
  const social = job?.social_links || {};

  return {
    facebook:
      social.facebook ||
      (viewUrl
        ? `https://www.facebook.com/sharer.php?u=${encodeURIComponent(viewUrl)}`
        : ''),
    linkedIn:
      social.linkedIn ||
      social.linkedin ||
      (viewUrl
        ? `http://www.linkedin.com/shareArticle?url=${encodeURIComponent(
            viewUrl,
          )}&title=${encodeURIComponent(title)}&mini=true`
        : ''),
    twitter:
      social.twitter ||
      (viewUrl
        ? `https://twitter.com/intent/tweet?url=${encodeURIComponent(
            viewUrl,
          )}&text=${encodeURIComponent(title)}`
        : ''),
    viewUrl,
  };
};

